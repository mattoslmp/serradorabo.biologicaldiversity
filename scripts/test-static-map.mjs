import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {mkdtemp,symlink,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
const basePath=(process.env.NEXT_PUBLIC_BASE_PATH||'').replace(/\/$/,'');
if(basePath&&!/^\/[a-zA-Z0-9._-]+$/.test(basePath))throw Error('Invalid project base path');
const servedRoot=basePath?await mkdtemp(path.join(tmpdir(),'itv-pages-test-')):path.resolve('out');
if(basePath)await symlink(path.resolve('out'),path.join(servedRoot,basePath.slice(1)),'dir');
const site='http://127.0.0.1:3100'+basePath+'/';
const server=spawn('python3',['-m','http.server','3100','--bind','127.0.0.1','--directory',servedRoot],{stdio:'ignore'});
let browser;
try{
 for(let i=0;i<50;i++){try{if((await fetch(site)).ok)break}catch{}await new Promise(r=>setTimeout(r,100))}
 browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(site);
 await page.getByRole('textbox',{name:'Usuário',exact:true}).fill('genomicaambiental');
 await page.getByRole('textbox',{name:'Senha',exact:true}).fill(process.env.ATLAS_INITIAL_PASSWORD);
 await page.getByRole('button',{name:'Entrar no atlas →',exact:true}).click();
 await page.waitForURL(u=>!u.pathname.includes('/login'),{timeout:60000});
 await page.waitForFunction(()=>document.body.innerText.includes('Mapa das amostras reais')||document.body.innerText.includes('Onde amostramos'),{},{timeout:60000});
 const bootstrap=await page.getByRole('heading',{name:'Mapa das amostras reais',exact:true}).isVisible();
 if(!bootstrap)await page.getByRole('button',{name:'Mapa',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.leaflet-overlay-pane path').length>=143,{},{timeout:30000});
 const alerts=(await page.getByRole('alert').allTextContents()).filter(x=>x.trim());
 if(alerts.length||errors.length)throw Error('Map render errors: '+[...alerts,...errors].join('; '));
 await page.getByRole('combobox',{name:'Campanha',exact:true}).selectOption('Chuvosa');
 await page.getByText(/35 bibliotecas no recorte/).first().waitFor();
 await page.waitForFunction(()=>document.querySelectorAll('.leaflet-overlay-pane path').length>=143);
 await page.getByRole('combobox',{name:'Campanha',exact:true}).selectOption('Todas');
 await page.getByText(/89 bibliotecas no recorte; 88 com coordenadas/).first().waitFor();
 console.log('PASS: real Supabase UI login; geographic polygons and GPS markers render; seasonal filter 89 → 35 → 89; one missing GPS stays missing.');
 if(!bootstrap){
  await page.getByRole('button',{name:'Heatmap',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.heatmaplayer image').length===4,{},{timeout:45000});
  await page.getByText('Famílias dos táxons exibidos',{exact:true}).waitFor();
  await page.getByRole('combobox',{name:'Nível taxonômico',exact:true}).selectOption('Family');
  await page.getByRole('button',{name:'Filogenia',exact:true}).click();
  await page.getByRole('combobox',{name:'Representantes por família',exact:true}).selectOption('1');
  const one=await page.locator('.treebox svg text').count();
  await page.getByRole('combobox',{name:'Representantes por família',exact:true}).selectOption('2');
  const two=await page.locator('.treebox svg text').count();
  if(!(one>0&&two>one))throw Error('Tree representative filter failed');
  if(await page.locator('.treebox svg circle').count()!==two*3)throw Error('Tree must have exactly three metadata rings');
  const clipped=await page.locator('.treebox svg text').evaluateAll(nodes=>nodes.some(n=>{const b=n.getBBox();return b.x<0||b.x+b.width>1600}));
  if(clipped)throw Error('Tree labels exceed SVG viewBox');
  await page.getByRole('button',{name:'Diferencial',exact:true}).click();
  await page.getByRole('combobox',{name:'Nível taxonômico',exact:true}).selectOption('Genus');
  await page.getByRole('combobox',{name:'Método',exact:true}).selectOption('ALDEx2');
  await page.getByRole('checkbox',{name:'Só q < 0,05'}).check();
  await page.getByRole('cell',{name:'Camptosema',exact:true}).waitFor();
  await page.getByRole('button',{name:'Diversidade alfa',exact:true}).click();
  await page.getByRole('heading',{name:'Comparações paramétricas e não paramétricas'}).waitFor();
  await page.getByRole('button',{name:'Diversidade beta',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.scatterlayer .point').length>0);
  await page.getByRole('button',{name:'Figuras',exact:true}).click();
  if(await page.locator('.figure-card').count()!==11)throw Error('Expected 11 actual figures');
  await page.getByRole('button',{name:'Tabelas',exact:true}).click();
  if(await page.getByRole('combobox',{name:'Tabela científica'}).locator('option').count()<100)throw Error('Scientific tables missing');
  if(errors.length)throw Error('Atlas UI errors: '+errors.join('; '));
  console.log('PASS: complete actual atlas; annotated heatmap; family/representative tree filters; three metadata rings; unclipped tree labels; ALDEx2 result; alpha/beta; 11 figures; all scientific tables.');
 }
 await page.getByRole('button',{name:/^Sair/}).click();
 await page.getByRole('textbox',{name:'Usuário',exact:true}).waitFor();
 if(new URL(page.url()).pathname!==basePath+'/login/')throw Error('Logout escaped the repository base path');
 console.log('PASS: logout returns to protected login within '+(basePath||'/')+'.');
}finally{await browser?.close();server.kill();if(basePath)await rm(servedRoot,{recursive:true,force:true});}
